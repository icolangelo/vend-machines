[CmdletBinding()]
param(
    [string]$PostgresImage = "postgres:17-alpine"
)

$ErrorActionPreference = "Stop"
Set-StrictMode -Version Latest

$containerName = "vendmachines-session-admission-test-$([Guid]::NewGuid().ToString('N'))"
$containerStarted = $false
$lockJob = $null

function Invoke-DockerChecked {
    param([Parameter(Mandatory = $true)][string[]]$Arguments)

    $output = & docker @Arguments 2>&1
    if ($LASTEXITCODE -ne 0) {
        $detail = ($output | Select-Object -Last 3 | Out-String).Trim()
        throw "Falha em fixture PostgreSQL descartável (código $LASTEXITCODE): $detail"
    }
    return $output
}

function Invoke-PsqlScript {
    param(
        [Parameter(Mandatory = $true)][string]$ScriptPath,
        [string[]]$Variables = @(),
        [string]$DatabaseUser = "session_admission_operator"
    )

    $arguments = @(
        "exec", $containerName, "psql", "-X", "-v", "ON_ERROR_STOP=1",
        "-U", $DatabaseUser, "-d", "session_admission_test"
    ) + $Variables + @("-f", $ScriptPath)
    $output = & docker @arguments 2>&1
    return @{ ExitCode = $LASTEXITCODE; Output = ($output | Out-String).Trim() }
}

function Invoke-PsqlQuery {
    param([Parameter(Mandatory = $true)][string]$Query)

    $output = Invoke-DockerChecked @(
        "exec", $containerName, "psql", "-X", "-A", "-t", "-v", "ON_ERROR_STOP=1",
        "-U", "postgres", "-d", "session_admission_test", "-c", $Query
    )
    return ($output | Out-String).Trim()
}

function Assert-AdmissionPaused {
    $state = Invoke-PsqlQuery 'SELECT "NewSessionsPaused" FROM "SessionAdmissionGates" WHERE "Id" = 1'
    if ($state -ne "t") {
        throw "A admissão deveria continuar pausada, mas o estado retornou '$state'."
    }
}

function Assert-ResumeBlocked {
    param(
        [Parameter(Mandatory = $true)][string]$ExpectedMessage,
        [Parameter(Mandatory = $true)][string]$CaseName
    )

    $result = Invoke-PsqlScript "/tmp/Resume-SessionAdmission.sql" @(
        "-v", "operator_name=synthetic-operator", "-v", "resume_reason=synthetic-test"
    )
    if ($result.ExitCode -eq 0 -or $result.Output -notmatch [regex]::Escape($ExpectedMessage)) {
        throw "A retomada deveria falhar em '$CaseName'; saída: $($result.Output)"
    }
    Assert-AdmissionPaused
}

try {
    Invoke-DockerChecked @(
        "run", "--rm", "--detach", "--network", "none", "--name", $containerName,
        "--env", "POSTGRES_PASSWORD=synthetic-session-admission-test-only", $PostgresImage
    ) | Out-Null
    $containerStarted = $true

    # The official PostgreSQL image briefly starts a temporary server while
    # initializing its data directory. Wait until the final server is ready.
    Start-Sleep -Seconds 5
    $ready = $false
    $consecutiveReadyChecks = 0
    $deadline = [DateTime]::UtcNow.AddSeconds(60)
    while ([DateTime]::UtcNow -lt $deadline) {
        & docker exec $containerName pg_isready -U postgres *> $null
        if ($LASTEXITCODE -eq 0) {
            $consecutiveReadyChecks++
            if ($consecutiveReadyChecks -ge 3) {
                $ready = $true
                break
            }
        } else {
            $consecutiveReadyChecks = 0
        }
        Start-Sleep -Milliseconds 500
    }
    if (-not $ready) {
        throw "O PostgreSQL sintético não ficou pronto de forma estável dentro de 60 segundos."
    }

    $schema = @'
CREATE DATABASE session_admission_test;
'@
    Invoke-DockerChecked @("exec", $containerName, "psql", "-X", "-v", "ON_ERROR_STOP=1", "-U", "postgres", "-c", $schema) | Out-Null
    $fixtureSql = @'
CREATE TABLE "SessionAdmissionGates" (
    "Id" integer PRIMARY KEY,
    "NewSessionsPaused" boolean NOT NULL,
    "UpdatedAt" timestamp with time zone NOT NULL DEFAULT now(),
    "UpdatedBy" character varying(128) NOT NULL,
    "Reason" character varying(256) NOT NULL
);
CREATE TABLE "Machines" ("Id" text PRIMARY KEY, "CompanyId" uuid NULL);
CREATE TABLE "MachineConnectionStates" (
    "MachineId" text NOT NULL,
    "CompanyId" uuid NOT NULL,
    "IsOnline" boolean NOT NULL DEFAULT false,
    "LastSeenAt" timestamp with time zone NULL,
    "ConnectionId" text NULL,
    "OwnerNodeId" text NULL,
    "OwnerConnectionId" text NULL,
    "CommandRoutingVersion" integer NULL
);
CREATE TABLE "MachineSessions" ("Id" integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, "State" text NOT NULL DEFAULT 'Opening', "StartedAt" timestamp with time zone NOT NULL DEFAULT now(), "ClosedAt" timestamp with time zone NULL);
CREATE TABLE "TelemetryCommandDispatches" ("Id" uuid PRIMARY KEY, "OwnerNodeId" text NOT NULL DEFAULT 'fixture-node', "Status" text NOT NULL, "Operation" text NOT NULL, "Error" text NULL);
CREATE TABLE "TelemetryCommands" ("Id" uuid PRIMARY KEY, "Status" text NOT NULL, "Error" text NULL, "CreatedAt" timestamp with time zone NOT NULL DEFAULT now());
CREATE TABLE "DeviceMessageInbox" ("Id" uuid PRIMARY KEY, "Status" text NOT NULL);
CREATE TABLE "WebhookInboxMessages" ("Id" uuid PRIMARY KEY, "Status" text NOT NULL);
CREATE TABLE "OutboxMessages" ("Id" uuid PRIMARY KEY, "Status" text NOT NULL);
CREATE TABLE "TelemetryCommandResolutions" (
    "Id" uuid PRIMARY KEY,
    "TelemetryCommandId" uuid NULL UNIQUE REFERENCES "TelemetryCommands"("Id"),
    "TelemetryCommandDispatchId" uuid NULL UNIQUE,
    "OperatorName" character varying(128) NOT NULL,
    "Reason" character varying(512) NOT NULL,
    "EvidenceReference" character varying(512) NOT NULL,
    "CreatedAt" timestamp with time zone NOT NULL,
    CHECK (("TelemetryCommandId" IS NOT NULL AND "TelemetryCommandDispatchId" IS NULL) OR
           ("TelemetryCommandId" IS NULL AND "TelemetryCommandDispatchId" IS NOT NULL))
);
CREATE TABLE "SystemSettings" ("Id" integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, "ApplicationFeePercent" numeric NOT NULL);
INSERT INTO "SessionAdmissionGates" ("Id", "NewSessionsPaused", "UpdatedBy", "Reason") VALUES (1, false, 'migration', 'default');
INSERT INTO "SystemSettings" ("ApplicationFeePercent") VALUES (10);
'@
    Invoke-DockerChecked @(
        "exec", $containerName, "psql", "-X", "-v", "ON_ERROR_STOP=1", "-U", "postgres",
        "-d", "session_admission_test", "-c", $fixtureSql
    ) | Out-Null
    $operatorPrivileges = @'
CREATE ROLE session_admission_operator LOGIN;
CREATE ROLE telemetry_command_resolution_operator LOGIN;
GRANT CONNECT ON DATABASE session_admission_test TO session_admission_operator;
GRANT USAGE ON SCHEMA public TO session_admission_operator;
GRANT SELECT ON "SessionAdmissionGates" TO session_admission_operator;
GRANT UPDATE ("NewSessionsPaused", "UpdatedAt", "UpdatedBy", "Reason") ON "SessionAdmissionGates" TO session_admission_operator;
GRANT SELECT ("ClosedAt", "StartedAt", "State") ON "MachineSessions" TO session_admission_operator;
GRANT SELECT ("Id", "CompanyId") ON "Machines" TO session_admission_operator;
GRANT SELECT ("MachineId", "CompanyId", "IsOnline", "LastSeenAt", "ConnectionId", "OwnerNodeId", "OwnerConnectionId", "CommandRoutingVersion") ON "MachineConnectionStates" TO session_admission_operator;
GRANT SELECT ("Id", "OwnerNodeId", "Status", "Operation", "Error") ON "TelemetryCommandDispatches" TO session_admission_operator;
GRANT SELECT ("Id", "Status", "Error") ON "TelemetryCommands" TO session_admission_operator;
GRANT SELECT ("Status") ON "DeviceMessageInbox" TO session_admission_operator;
GRANT SELECT ("Status") ON "WebhookInboxMessages" TO session_admission_operator;
GRANT SELECT ("Status") ON "OutboxMessages" TO session_admission_operator;
GRANT SELECT ("TelemetryCommandId", "TelemetryCommandDispatchId") ON "TelemetryCommandResolutions" TO session_admission_operator;
GRANT INSERT ON "TelemetryCommandResolutions" TO session_admission_operator;
GRANT SELECT ("ApplicationFeePercent") ON "SystemSettings" TO session_admission_operator;
GRANT CONNECT ON DATABASE session_admission_test TO telemetry_command_resolution_operator;
GRANT USAGE ON SCHEMA public TO telemetry_command_resolution_operator;
GRANT SELECT ("Id", "OwnerNodeId", "Status", "Operation", "Error") ON "TelemetryCommandDispatches" TO telemetry_command_resolution_operator;
GRANT SELECT ("Id", "Status", "Error", "CreatedAt") ON "TelemetryCommands" TO telemetry_command_resolution_operator;
GRANT UPDATE ("Status", "Error") ON "TelemetryCommands" TO telemetry_command_resolution_operator;
GRANT SELECT ("TelemetryCommandId", "TelemetryCommandDispatchId") ON "TelemetryCommandResolutions" TO telemetry_command_resolution_operator;
GRANT INSERT ON "TelemetryCommandResolutions" TO telemetry_command_resolution_operator;
'@
    Invoke-DockerChecked @(
        "exec", $containerName, "psql", "-X", "-v", "ON_ERROR_STOP=1", "-U", "postgres",
        "-d", "session_admission_test", "-c", $operatorPrivileges
    ) | Out-Null
    Invoke-DockerChecked @("cp", (Join-Path $PSScriptRoot "Pause-SessionAdmission.sql"), "${containerName}:/tmp/Pause-SessionAdmission.sql") | Out-Null
    Invoke-DockerChecked @("cp", (Join-Path $PSScriptRoot "Resume-SessionAdmission.sql"), "${containerName}:/tmp/Resume-SessionAdmission.sql") | Out-Null
    Invoke-DockerChecked @("cp", (Join-Path $PSScriptRoot "Resolve-TelemetryCommand.sql"), "${containerName}:/tmp/Resolve-TelemetryCommand.sql") | Out-Null
    Invoke-DockerChecked @("cp", (Join-Path $PSScriptRoot "List-UnresolvedTelemetryCommands.sql"), "${containerName}:/tmp/List-UnresolvedTelemetryCommands.sql") | Out-Null

    $missingResumeArguments = Invoke-PsqlScript "/tmp/Resume-SessionAdmission.sql"
    if ($missingResumeArguments.ExitCode -eq 0 -or $missingResumeArguments.Output -notmatch "operator_name_required") {
        throw "A retomada sem identificação do operador deveria terminar com erro: $($missingResumeArguments.Output)"
    }

    $missingArguments = Invoke-PsqlScript "/tmp/Pause-SessionAdmission.sql"
    if ($missingArguments.ExitCode -eq 0 -or $missingArguments.Output -notmatch "operator_name_required") {
        throw "A pausa sem identificação do operador deveria terminar com erro: $($missingArguments.Output)"
    }

    $lockJob = Start-Job -ArgumentList $containerName -ScriptBlock {
        param($name)
        & docker exec $name psql -X -v ON_ERROR_STOP=1 -U session_admission_operator -d session_admission_test `
            -c 'BEGIN; SELECT "NewSessionsPaused" FROM "SessionAdmissionGates" WHERE "Id" = 1 FOR SHARE; SELECT pg_sleep(3); COMMIT;'
        if ($LASTEXITCODE -ne 0) {
            throw "Não foi possível manter a admissão compartilhada durante o teste."
        }
    }
    $lockIsHeld = $false
    for ($attempt = 0; $attempt -lt 60; $attempt++) {
        $activeLockQuery = Invoke-PsqlQuery "SELECT count(*) FROM pg_stat_activity WHERE pid <> pg_backend_pid() AND state = 'active' AND query LIKE '%pg_sleep(3)%'"
        if ($activeLockQuery -eq "1") {
            $lockIsHeld = $true
            break
        }
        Start-Sleep -Milliseconds 50
    }
    if (-not $lockIsHeld) {
        throw "O ensaio não confirmou que a transação já mantinha FOR SHARE."
    }
    $pauseStartedAt = [DateTime]::UtcNow
    $pause = Invoke-PsqlScript "/tmp/Pause-SessionAdmission.sql" @(
        "-v", "operator_name=synthetic-operator", "-v", "pause_reason=synthetic-test"
    )
    $pauseElapsed = [DateTime]::UtcNow - $pauseStartedAt
    $lockJobResult = Wait-Job -Job $lockJob -Timeout 10
    if ($null -eq $lockJobResult) {
        throw "O ensaio de lock compartilhado excedeu 10 segundos."
    }
    $lockOutput = Receive-Job -Job $lockJob
    Remove-Job -Job $lockJob
    $lockJob = $null
    if ($lockOutput -match "Exception|ERROR") {
        throw "O ensaio de lock compartilhado falhou: $lockOutput"
    }
    if ($pause.ExitCode -ne 0 -or $pause.Output -notmatch "\st\s+\|") {
        throw "A pausa válida deveria concluir: $($pause.Output)"
    }
    if ($pauseElapsed.TotalMilliseconds -lt 1500) {
        throw "A pausa não esperou a operação admitida que manteve FOR SHARE ($([int]$pauseElapsed.TotalMilliseconds) ms)."
    }

    Invoke-DockerChecked @(
        "exec", $containerName, "psql", "-X", "-v", "ON_ERROR_STOP=1", "-U", "postgres",
        "-d", "session_admission_test", "-c", 'INSERT INTO "MachineSessions" ("ClosedAt") VALUES (NULL)'
    ) | Out-Null
    Assert-ResumeBlocked "Venda fisica aberta" "venda aberta"
    Invoke-PsqlQuery 'DELETE FROM "MachineSessions"' | Out-Null

    Invoke-PsqlQuery 'INSERT INTO "MachineSessions" ("State", "ClosedAt") VALUES (''ClosureIncomplete'', now())' | Out-Null
    Assert-ResumeBlocked "Encerramento fisico sem confirmacao" "encerramento físico incompleto"
    Invoke-PsqlQuery 'UPDATE "MachineSessions" SET "State" = ''ClosureVerified''' | Out-Null
    $resumeAfterVerifiedClosure = Invoke-PsqlScript "/tmp/Resume-SessionAdmission.sql" @(
        "-v", "operator_name=synthetic-operator", "-v", "resume_reason=synthetic-test"
    )
    if ($resumeAfterVerifiedClosure.ExitCode -ne 0 -or $resumeAfterVerifiedClosure.Output -notmatch "\s+f\s+\|") {
        throw "A retomada deveria permitir somente após confirmação auditada do encerramento: $($resumeAfterVerifiedClosure.Output)"
    }
    Invoke-PsqlScript "/tmp/Pause-SessionAdmission.sql" @(
        "-v", "operator_name=synthetic-operator", "-v", "pause_reason=synthetic-test"
    ) | Out-Null
    Invoke-PsqlQuery 'DELETE FROM "MachineSessions"' | Out-Null

    $uncertainDispatchId = "22222222-2222-2222-2222-222222222222"
    $insertUncertainDispatch = 'INSERT INTO "TelemetryCommandDispatches" ("Id", "Status", "Operation") VALUES (''{0}'', ''Indeterminate'', ''Command'')' -f $uncertainDispatchId
    Invoke-PsqlQuery $insertUncertainDispatch | Out-Null
    Assert-ResumeBlocked "Comando MDB mutavel" "comando indeterminado"
    $unresolvedList = Invoke-PsqlScript "/tmp/List-UnresolvedTelemetryCommands.sql"
    if ($unresolvedList.ExitCode -ne 0 -or $unresolvedList.Output -notmatch $uncertainDispatchId) {
        throw "A listagem restrita deveria identificar somente o UUID do dispatch: $($unresolvedList.Output)"
    }
    $resolvedDispatch = Invoke-PsqlScript "/tmp/Resolve-TelemetryCommand.sql" @(
        "-v", "dispatch_id=$uncertainDispatchId", "-v", "operator_name=synthetic-operator",
        "-v", "resolution_reason=synthetic-review", "-v", "evidence_reference=synthetic-ticket-0"
    ) -DatabaseUser "telemetry_command_resolution_operator"
    if ($resolvedDispatch.ExitCode -ne 0 -or $resolvedDispatch.Output -notmatch $uncertainDispatchId) {
        throw "A reconciliação auditada do dispatch incerto deveria concluir: $($resolvedDispatch.Output)"
    }

    $uncertainCommandId = "11111111-1111-1111-1111-111111111111"
    $insertUncertainCommand = 'INSERT INTO "TelemetryCommands" ("Id", "Status", "Error") VALUES (''{0}'', ''failed'', ''ack_timeout'')' -f $uncertainCommandId
    Invoke-PsqlQuery $insertUncertainCommand | Out-Null
    Assert-ResumeBlocked "Comando MDB mutavel nao resolvido" "ACK local incerto"
    $unresolvedList = Invoke-PsqlScript "/tmp/List-UnresolvedTelemetryCommands.sql"
    if ($unresolvedList.ExitCode -ne 0 -or
        $unresolvedList.Output -match $uncertainDispatchId -or
        $unresolvedList.Output -notmatch $uncertainCommandId) {
        throw "A listagem restrita deveria incluir somente os resultados ainda não reconciliados: $($unresolvedList.Output)"
    }
    $resolvedCommand = Invoke-PsqlScript "/tmp/Resolve-TelemetryCommand.sql" @(
        "-v", "command_id=$uncertainCommandId", "-v", "operator_name=synthetic-operator",
        "-v", "resolution_reason=synthetic-review", "-v", "evidence_reference=synthetic-ticket-1"
    ) -DatabaseUser "telemetry_command_resolution_operator"
    if ($resolvedCommand.ExitCode -ne 0 -or $resolvedCommand.Output -notmatch $uncertainCommandId) {
        throw "A reconciliação auditada do comando incerto deveria concluir: $($resolvedCommand.Output)"
    }
    $resolutionCount = Invoke-PsqlQuery 'SELECT count(*) FROM "TelemetryCommandResolutions"'
    if ($resolutionCount -ne "2") {
        throw "A reconciliação deveria preservar um registro de auditoria; contagem: $resolutionCount"
    }

    $failedDispatchId = "44444444-4444-4444-4444-444444444444"
    $insertFailedDispatch = 'INSERT INTO "TelemetryCommandDispatches" ("Id", "Status", "Operation", "Error") VALUES (''{0}'', ''Failed'', ''Command'', ''ack_timeout'')' -f $failedDispatchId
    Invoke-PsqlQuery $insertFailedDispatch | Out-Null
    Assert-ResumeBlocked "Comando MDB mutavel nao resolvido" "ACK remoto incerto"
    $failedRemoteResolution = Invoke-PsqlScript "/tmp/Resolve-TelemetryCommand.sql" @(
        "-v", "dispatch_id=$failedDispatchId", "-v", "operator_name=synthetic-operator",
        "-v", "resolution_reason=synthetic-review", "-v", "evidence_reference=synthetic-ticket-2"
    ) -DatabaseUser "telemetry_command_resolution_operator"
    if ($failedRemoteResolution.ExitCode -ne 0 -or $failedRemoteResolution.Output -notmatch $failedDispatchId) {
        throw "A reconciliação auditada do ACK remoto incerto deveria concluir: $($failedRemoteResolution.Output)"
    }
    $resolutionCount = Invoke-PsqlQuery 'SELECT count(*) FROM "TelemetryCommandResolutions"'
    if ($resolutionCount -ne "3") {
        throw "A reconciliação remota deveria preservar seu registro de auditoria; contagem: $resolutionCount"
    }

    Invoke-PsqlQuery 'UPDATE "SystemSettings" SET "ApplicationFeePercent" = 100' | Out-Null
    Assert-ResumeBlocked "invalid_platform_fee_setting_blocks_resume" "taxa inválida"
    Invoke-PsqlQuery 'UPDATE "SystemSettings" SET "ApplicationFeePercent" = 10' | Out-Null

    Invoke-PsqlQuery 'INSERT INTO "DeviceMessageInbox" ("Id", "Status") VALUES (''55555555-5555-5555-5555-555555555555'', ''Failed'')' | Out-Null
    Assert-ResumeBlocked "Mensagens de telemetria nao processadas" "mensagem MDB não processada"
    Invoke-PsqlQuery 'UPDATE "DeviceMessageInbox" SET "Status" = ''Processed''' | Out-Null

    Invoke-PsqlQuery 'INSERT INTO "WebhookInboxMessages" ("Id", "Status") VALUES (''66666666-6666-6666-6666-666666666666'', ''Failed'')' | Out-Null
    Assert-ResumeBlocked "Webhooks de pagamento nao processados" "webhook não processado"
    Invoke-PsqlQuery 'UPDATE "WebhookInboxMessages" SET "Status" = ''Processed''' | Out-Null

    Invoke-PsqlQuery 'INSERT INTO "OutboxMessages" ("Id", "Status") VALUES (''77777777-7777-7777-7777-777777777777'', ''processing'')' | Out-Null
    Assert-ResumeBlocked "Operacao financeira ainda esta em processamento" "outbox financeira em andamento"
    Invoke-PsqlQuery 'UPDATE "OutboxMessages" SET "Status" = ''failed''' | Out-Null

    Invoke-PsqlQuery 'INSERT INTO "TelemetryCommandDispatches" ("Id", "Status", "Operation") VALUES (''33333333-3333-3333-3333-333333333333'', ''Indeterminate'', ''MdbStatus'')' | Out-Null
    $resume = Invoke-PsqlScript "/tmp/Resume-SessionAdmission.sql" @(
        "-v", "operator_name=synthetic-operator", "-v", "resume_reason=synthetic-test"
    )
    if ($resume.ExitCode -ne 0 -or $resume.Output -notmatch "\sf\s+\|") {
        throw "A retomada válida com consulta MDB somente leitura deveria concluir: $($resume.Output)"
    }

    $alreadyOpen = Invoke-PsqlScript "/tmp/Resume-SessionAdmission.sql" @(
        "-v", "operator_name=synthetic-operator", "-v", "resume_reason=synthetic-test"
    )
    if ($alreadyOpen.ExitCode -eq 0 -or $alreadyOpen.Output -notmatch "Admissao ja estava aberta") {
        throw "A repetição da retomada deveria falhar: $($alreadyOpen.Output)"
    }

    Invoke-PsqlQuery 'DROP TABLE "SessionAdmissionGates"' | Out-Null
    foreach ($script in @("/tmp/Pause-SessionAdmission.sql", "/tmp/Resume-SessionAdmission.sql")) {
        $missingGate = Invoke-PsqlScript $script @(
            "-v", "operator_name=synthetic-operator", "-v", "pause_reason=synthetic-test",
            "-v", "resume_reason=synthetic-test"
        )
        if ($missingGate.ExitCode -eq 0) {
            throw "O script '$script' deveria falhar quando o registro de controle está ausente."
        }
    }

    Write-Host "Scripts de pausa/retomada aprovados: parâmetros, vendas/encerramentos, comandos/mensagens pendentes, confirmação auditada, registro ausente e falhas com código não zero."
}
finally {
    if ($null -ne $lockJob) {
        Stop-Job -Job $lockJob -ErrorAction SilentlyContinue
        Remove-Job -Job $lockJob -Force -ErrorAction SilentlyContinue
    }
    if ($containerStarted) {
        & docker stop $containerName *> $null
        if ($LASTEXITCODE -ne 0) {
            & docker rm --force $containerName *> $null
        }
    }
}
